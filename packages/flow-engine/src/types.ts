// ── Graph Structures ──────────────────────────────────────────────────────────

export interface FlowNode {
  id: string;
  type: NodeType;
  label?: string;
  config: NodeConfig;
  /** Visual position on the canvas */
  position?: { x: number; y: number };
}

export interface FlowEdge {
  id: string;
  /** Source node id */
  source: string;
  /** Target node id */
  target: string;
  /**
   * Output port from source node:
   * - 'default' — normal/fallthrough
   * - 'true' / 'false' — from IF_CONDITION
   * - 'outside' — from SEND_WINDOW (outside time window)
   * - 'excluded' — from SEGMENT_QUALITY_GATE
   * - string index — from KEYWORD_ROUTER ('0', '1', etc.)
   */
  sourcePort?: string;
}

export interface FlowDefinition {
  nodes: FlowNode[];
  edges: FlowEdge[];
}

// ── Condition Types ───────────────────────────────────────────────────────────

export type ConditionOperator =
  | 'equals'
  | 'not_equals'
  | 'contains'
  | 'not_contains'
  | 'greater_than'
  | 'less_than'
  | 'is_set'
  | 'is_not_set'
  | 'days_since'
  | 'includes_tag'
  | 'not_includes_tag';

export type ConditionField =
  | 'buyer.name'
  | 'buyer.phone'
  | 'buyer.totalOrders'
  | 'buyer.tags'
  | 'buyer.lastOrderAt'
  | 'trigger.type'
  | 'trigger.buttonPayload'
  | `flow.variable.${string}`
  | `answers.${string}`;

export interface Condition {
  field: ConditionField | string;
  operator: ConditionOperator;
  value?: string | number | boolean;
}

export interface ConditionGroup {
  logic: 'AND' | 'OR';
  conditions: Condition[];
}

// ── Execution Context ─────────────────────────────────────────────────────────

export interface BuyerContext {
  id: string;
  waPhone: string;
  name: string;
  totalOrders: number;
  tags: string[];
  lastOrderAt?: Date | null;
  doNotContact: boolean;
  preferredLanguage: string;
  notes?: string | null;
  displayName?: string | null;
  activeFlowCount: number;
}

export interface TriggerContext {
  type: TriggerType | 'order_event';
  buttonPayload?: string;
  messageText?: string;
  conversationId?: string;
  /** Set when triggered by an order lifecycle event */
  orderId?: string;
}

export interface ExecutionContext {
  executionId: string;
  flowId: string;
  tenantId: string;
  buyerId: string;
  buyer: BuyerContext;
  trigger: TriggerContext;
  /** Flow-scoped runtime variables. COLLECT_INFO stores answers here as 'answers.{variableName}'. */
  variables: Record<string, unknown>;
  executionLog: ExecutionLogEntry[];
  wabaId?: string;
}

export interface ExecutionLogEntry {
  nodeId: string;
  nodeType: NodeType;
  timestamp: string;
  status: 'ok' | 'skipped' | 'error' | 'waiting';
  skipReason?: string;
  error?: string;
  meta?: Record<string, unknown>;
}

